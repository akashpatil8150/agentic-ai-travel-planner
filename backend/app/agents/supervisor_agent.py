import json
import logging
from typing import List, Literal

from pydantic import BaseModel, Field

from app.services.llm.llm_client import (
    LLMClient,
    LLMClientError,
)

from app.state.trip_state import TripState


logger = logging.getLogger(__name__)


# ============================================================
# SUPERVISOR PLAN SCHEMAS
# ============================================================


class AgentTask(BaseModel):
    """
    Task assigned by Supervisor to a specialized agent.
    """

    agent: Literal[
        "transport",
        "hotel",
        "places",
        "weather",
    ]

    task: str = Field(
        min_length=1,
        max_length=500,
    )

    priority: Literal[
        "high",
        "medium",
        "low",
    ] = "medium"


class SupervisorPlan(BaseModel):
    """
    Structured plan generated by Supervisor LLM.
    """

    tasks: List[AgentTask]

    execution_mode: Literal[
        "parallel",
        "sequential",
    ] = "parallel"

    reason: str = Field(
        min_length=1,
        max_length=1000,
    )


# ============================================================
# SUPERVISOR AGENT
# ============================================================


class SupervisorAgent:
    """
    LLM-based Supervisor Agent.

    Responsibilities:
        1. Analyze TripState
        2. Decide which specialized agents are required
        3. Generate tasks for those agents
        4. Decide execution mode
        5. Return structured execution plan

    Does NOT:
        - call external APIs
        - perform booking
        - modify prices
        - override constraints
        - access JWT/security information
        - execute agents directly
    """

    ALLOWED_AGENTS = {
        "transport",
        "hotel",
        "places",
        "weather",
    }

    def __init__(self):

        self.llm = LLMClient()

        logger.info(
            "SupervisorAgent initialized"
        )

    # ========================================================
    # RUN
    # ========================================================

    def run(
        self,
        state: TripState,
    ) -> SupervisorPlan:

        logger.info(
            "Supervisor Agent started"
        )

        if not isinstance(
            state,
            TripState,
        ):
            raise TypeError(
                "SupervisorAgent expects a TripState object."
            )

        # ----------------------------------------------------
        # BUILD SAFE CONTEXT
        # ----------------------------------------------------

        context = self._build_safe_context(
            state
        )

        # ----------------------------------------------------
        # SYSTEM PROMPT
        # ----------------------------------------------------

        system_prompt = """
You are the Supervisor Agent of an Agentic AI Travel Planner.

Your job is to create an execution plan for specialized
travel agents.

Available agents:

1. transport
   - Finds flights, trains and other transport
   - Handles transport preferences

2. hotel
   - Finds accommodation
   - Considers budget and traveler requirements

3. places
   - Finds attractions and activities
   - Considers user interests and preferences

4. weather
   - Retrieves weather information
   - Helps assess travel conditions

Rules:

- Use ONLY the available agents.
- Do not invent agent names.
- Assign only necessary tasks.
- Do not perform API calls yourself.
- Do not make booking decisions.
- Do not expose or request private user information.
- Transport, hotel, places and weather can normally run
  in parallel because they are independent.
- Keep tasks concise and actionable.
- Return the execution plan using the required JSON schema.
"""

        # ----------------------------------------------------
        # USER PROMPT
        # ----------------------------------------------------

        user_prompt = f"""
Create the execution plan for this travel request.

Trip context:

{json.dumps(
    context,
    indent=2,
    ensure_ascii=False,
)}

Decide which specialized agents are actually required.

For each selected agent:
- assign one clear task
- assign priority
- do not include unnecessary agents

Use parallel execution when the selected agents are independent.
"""

        # ----------------------------------------------------
        # STRUCTURED OUTPUT SCHEMA
        # ----------------------------------------------------

        supervisor_schema = {
            "type": "object",

            "properties": {
                "tasks": {
                    "type": "array",

                    "items": {
                        "type": "object",

                        "properties": {
                            "agent": {
                                "type": "string",
                                "enum": [
                                    "transport",
                                    "hotel",
                                    "places",
                                    "weather",
                                ],
                            },

                            "task": {
                                "type": "string",
                            },

                            "priority": {
                                "type": "string",
                                "enum": [
                                    "high",
                                    "medium",
                                    "low",
                                ],
                            },
                        },

                        "required": [
                            "agent",
                            "task",
                            "priority",
                        ],

                        "additionalProperties": False,
                    },
                },

                "execution_mode": {
                    "type": "string",
                    "enum": [
                        "parallel",
                        "sequential",
                    ],
                },

                "reason": {
                    "type": "string",
                },
            },

            "required": [
                "tasks",
                "execution_mode",
                "reason",
            ],

            "additionalProperties": False,
        }

        response_format = {
            "type": "json_schema",

            "json_schema": {
                "name": "supervisor_plan",

                "strict": True,

                "schema": supervisor_schema,
            },
        }

        # ----------------------------------------------------
        # CALL LLM
        # ----------------------------------------------------

        try:

            response = self.llm.generate(
                system_prompt=system_prompt,

                user_prompt=user_prompt,

                temperature=0.0,

                max_tokens=350,

                reasoning_effort="low",

                response_format=response_format,
            )

        except LLMClientError as exc:

            logger.error(
                "Supervisor LLM failed | error=%s",
                exc,
            )

            return self._fallback_plan(
                state
            )

        # ----------------------------------------------------
        # PARSE STRUCTURED RESPONSE
        # ----------------------------------------------------

        try:

            raw_plan = self._parse_json_response(
                response
            )

            plan = SupervisorPlan.model_validate(
                raw_plan
            )

        except Exception as exc:

            logger.warning(
                "Invalid Supervisor LLM output | error=%s",
                exc,
            )

            return self._fallback_plan(
                state
            )

        # ----------------------------------------------------
        # SECURITY / AGENT WHITELIST
        # ----------------------------------------------------

        for task in plan.tasks:

            if task.agent not in self.ALLOWED_AGENTS:

                logger.warning(
                    "Supervisor attempted invalid agent: %s",
                    task.agent,
                )

                return self._fallback_plan(
                    state
                )

        # ----------------------------------------------------
        # REMOVE DUPLICATE AGENTS
        # ----------------------------------------------------

        unique_tasks = []

        seen_agents = set()

        for task in plan.tasks:

            if task.agent in seen_agents:
                continue

            seen_agents.add(
                task.agent
            )

            unique_tasks.append(
                task
            )

        plan.tasks = unique_tasks

        # ----------------------------------------------------
        # FINAL LOG
        # ----------------------------------------------------

        logger.info(
            "Supervisor plan generated | "
            "agents=%s | mode=%s | reason=%s",
            [
                task.agent
                for task in plan.tasks
            ],
            plan.execution_mode,
            plan.reason,
        )

        for task in plan.tasks:

            logger.info(
                "Supervisor task | "
                "agent=%s | "
                "priority=%s | "
                "task=%s",
                task.agent,
                task.priority,
                task.task,
            )

        return plan

    # ========================================================
    # SAFE JSON PARSER
    # ========================================================

    @staticmethod
    def _parse_json_response(
        response: str,
    ) -> dict:

        if not response:
            raise ValueError(
                "Supervisor returned empty response."
            )

        cleaned = response.strip()

        # ----------------------------------------------------
        # REMOVE MARKDOWN JSON FENCES
        # ----------------------------------------------------

        if cleaned.startswith(
            "```json"
        ):

            cleaned = cleaned[
                len("```json"):
            ]

        elif cleaned.startswith(
            "```"
        ):

            cleaned = cleaned[
                len("```"):
            ]

        if cleaned.endswith(
            "```"
        ):

            cleaned = cleaned[
                :-len("```")
            ]

        cleaned = cleaned.strip()

        # ----------------------------------------------------
        # DIRECT JSON PARSE
        # ----------------------------------------------------

        try:

            result = json.loads(
                cleaned
            )

            if not isinstance(
                result,
                dict,
            ):
                raise ValueError(
                    "Supervisor JSON must be an object."
                )

            return result

        except json.JSONDecodeError:

            # ------------------------------------------------
            # FALLBACK: EXTRACT OBJECT
            # ------------------------------------------------

            start = cleaned.find(
                "{"
            )

            end = cleaned.rfind(
                "}"
            )

            if (
                start == -1
                or end == -1
                or end <= start
            ):
                raise

            extracted = cleaned[
                start : end + 1
            ]

            result = json.loads(
                extracted
            )

            if not isinstance(
                result,
                dict,
            ):
                raise ValueError(
                    "Supervisor JSON must be an object."
                )

            return result

    # ========================================================
    # SAFE CONTEXT
    # ========================================================

    @staticmethod
    def _build_safe_context(
        state: TripState,
    ) -> dict:

        travelers = state.travelers

        return {
            "origin": (
                state.origin.name
                if state.origin
                else None
            ),

            "destination": (
                state.destination.name
                if state.destination
                else None
            ),

            "travel_dates": {
                "start": (
                    str(
                        state.travel_dates.start
                    )
                    if state.travel_dates
                    else None
                ),

                "end": (
                    str(
                        state.travel_dates.end
                    )
                    if state.travel_dates
                    else None
                ),
            },

            "travelers": {
                "adults": (
                    travelers.adults
                    if travelers
                    else 0
                ),

                "children": (
                    travelers.children
                    if travelers
                    else 0
                ),
            },

            "budget": {
                "amount": (
                    state.budget.amount
                    if state.budget
                    else None
                ),

                "currency": (
                    state.budget.currency
                    if state.budget
                    else "INR"
                ),
            },

            "preferences": (
                state.preferences or []
            ),
        }

    # ========================================================
    # FALLBACK PLAN
    # ========================================================

    @staticmethod
    def _fallback_plan(
        state: TripState,
    ) -> SupervisorPlan:

        tasks = []

        # ----------------------------------------------------
        # TRANSPORT
        # ----------------------------------------------------

        if (
            state.origin
            and state.destination
            and state.travel_dates
        ):

            tasks.append(
                AgentTask(
                    agent="transport",

                    task=(
                        "Find suitable transport "
                        "options between origin "
                        "and destination."
                    ),

                    priority="high",
                )
            )

        # ----------------------------------------------------
        # HOTEL
        # ----------------------------------------------------

        if (
            state.destination
            and state.travel_dates
            and (
                state.travel_dates.start
                != state.travel_dates.end
            )
        ):

            tasks.append(
                AgentTask(
                    agent="hotel",

                    task=(
                        "Find suitable accommodation "
                        "within the requested budget."
                    ),

                    priority="high",
                )
            )

        # ----------------------------------------------------
        # PLACES
        # ----------------------------------------------------

        if state.destination:

            tasks.append(
                AgentTask(
                    agent="places",

                    task=(
                        "Find places and activities "
                        "matching user preferences."
                    ),

                    priority="medium",
                )
            )

        # ----------------------------------------------------
        # WEATHER
        # ----------------------------------------------------

        if (
            state.destination
            and state.travel_dates
        ):

            tasks.append(
                AgentTask(
                    agent="weather",

                    task=(
                        "Retrieve weather information "
                        "for the destination and "
                        "travel dates."
                    ),

                    priority="medium",
                )
            )

        logger.warning(
            "Using deterministic Supervisor fallback"
        )

        return SupervisorPlan(
            tasks=tasks,

            execution_mode="parallel",

            reason=(
                "Fallback plan generated because "
                "Supervisor LLM was unavailable."
            ),
        )